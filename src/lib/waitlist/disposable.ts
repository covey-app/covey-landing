/**
 * True when the (already normalized) address is at a throwaway-inbox domain
 * or any subdomain of one. Privacy relays that forward to a real inbox —
 * Apple Hide My Email, DuckDuckGo, Firefox Relay, SimpleLogin, addy.io — are
 * deliberately NOT here: those people can be reached, and iOS users get
 * privaterelay.appleid.com addresses by default.
 */
export function isDisposableEmail(email: string): boolean {
  const at = email.lastIndexOf("@");
  if (at < 0) return false;
  const labels = email.slice(at + 1).toLowerCase().replace(/\.+$/, "").split(".");
  for (let i = 0; i < labels.length - 1; i++) {
    if (DISPOSABLE_DOMAINS.has(labels.slice(i).join("."))) return true;
  }
  return false;
}
